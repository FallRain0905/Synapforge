-- 026_agent_turn_outputs.sql
-- 「我的智能体」的**对话产出**（2026-09-24 用户需求：生成的文件要能下载或转进云盘）。
--
-- 背景：任务/运行那条线（CL-1）早就把执行体产出采集成成果物了，**对话这条线一直是空的**——
-- 执行体在对话里写了文件，人看不到也拿不到。这一列记"这一轮产出了哪些成果物"：
--   * 内容仍在成果物表与对象存储里（`artifacts`），这一列只存 id + 名字 + 大小 + 类型 + MIME；
--   * 与 `artifact_ids`（**输入**附件）分开两列：语义相反，混在一起历史就分不清谁进谁出；
--   * 成果物状态是 PENDING_REVIEW：产出照旧要过人工审核那道门，**对话通道不例外**。
--
-- 幂等：内核用 `artifact-create:chat:{turn_id}:{sha(相对路径+内容哈希)}` 做键，
-- 同一条路径在不同轮次写出不同内容时各成一个成果物，不会因"键相同、指纹不同"被判冲突。

ALTER TABLE agent_turns ADD COLUMN IF NOT EXISTS outputs text NOT NULL DEFAULT '[]';